def book(key,title,code,edition,units,extras):
    number=0; rows=[]
    for index,raw in enumerate(units,1):
        lessons=[]
        for line in raw.split('|'):
            parts=line.split('/')
            number+=1
            lessons.append(dict(id=f'{key}-{number:02}',number=number,title=parts[0],author=parts[1] if len(parts)>1 else '',focus=parts[2].split('、') if len(parts)>2 else []))
