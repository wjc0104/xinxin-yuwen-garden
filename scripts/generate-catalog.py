        if index in extras:
            poems=[]
            for j,line in enumerate(extras[index].split('|'),1):
                p=line.split('/')
                poems.append(dict(id=f'{key}-extra{index}-{j}',number=0,title=p[0],author=p[1],focus=['课外古诗词诵读']))
            rows.append(dict(id=f'{key}-extra{index}',title='课外古诗词诵读',lessons=poems))
